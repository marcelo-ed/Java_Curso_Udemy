package fundamentos;

public class Inferencia {
	public static void main(String[] args) {
		double a = 4.5;
		System.out.println(a);
		a = 11.52;
		System.out.println(a);
		
		var b = 5.75;
		System.out.println(b);
		
		var c = "texto";
		System.out.println(c);
		c = "outro texto";
		System.out.println(c);
		
		double d; // A variável foi declarada aqui;
		d = 4.5; // Foi inicializada (definida) aqui;
		System.out.println(d); // Foi usada aqui.
		
		
		float x = 3.14f;
		System.out.println(x);
	}
}
