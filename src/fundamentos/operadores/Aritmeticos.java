package fundamentos.operadores;

public class Aritmeticos {
	public static void main(String[] args) {
		System.out.println(6 + 3);
		
		var x = 35.12;
		double y = 65.15;
		
		System.out.println(x + y);
		System.out.println(x - y);
		System.out.println(x * y);
		System.out.println(x / y);
		
		
		System.out.println(8 % 3);
	}
}
